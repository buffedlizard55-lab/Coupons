  function renderSourcesView() {
    var host = document.getElementById("source-groups");
    host.textContent = "";
    var byUrl = {};
    ENTRIES.forEach(function (e) {
      (e.sources || []).forEach(function (s) {
        var key = s.url;
        if (!byUrl[key]) byUrl[key] = { source: s, entries: [] };
        if (!byUrl[key].entries.some(function (x) { return x.id === e.id; })) byUrl[key].entries.push(e);
      });
    });
    var groups = Object.keys(byUrl).map(function (k) { return byUrl[k]; });
    groups.sort(function (a, b) {
      return a.source.publisher.localeCompare(b.source.publisher) || a.source.url.localeCompare(b.source.url);
    });

    groups.forEach(function (g) {
      var domain = g.source.url.split("/")[2] || g.source.url;
      host.appendChild(el("div", { class: "source-row" }, [
        el("p", { class: "title" }, [el("a", { href: g.source.url, rel: "noopener noreferrer external", target: "_blank", text: g.source.title || g.source.url })]),
        el("p", { class: "meta", text: g.source.publisher + " \u00b7 " + domain + " \u00b7 checked " + g.source.accessed + " \u00b7 method: " + g.source.method }),
        el("p", { class: "entries", text: "Cited by " + g.entries.length + " entr" + (g.entries.length === 1 ? "y" : "ies") + ": " + g.entries.map(function (e) { return e.title; }).join(" | ") }),
        el("details", {}, [
          el("summary", { text: "Show the evidence that was read from this page" }),
          el("p", { class: "evidence", text: g.source.evidence })
        ])
      ]));
    });
  }

