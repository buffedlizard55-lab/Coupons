  var VIEWS = ["browse", "flags", "excluded", "sources", "method", "next"];

  function showView(name) {
    if (VIEWS.indexOf(name) === -1) name = "browse";
    VIEWS.forEach(function (v) {
      var node = document.getElementById("view-" + v);
      var isActive = v === name;
      node.classList.toggle("is-active", isActive);
      node.hidden = !isActive;
    });
    Array.prototype.forEach.call(document.querySelectorAll(".tab"), function (t) {
      var active = t.dataset.view === name;
      t.classList.toggle("is-active", active);
      if (active) t.setAttribute("aria-current", "page"); else t.removeAttribute("aria-current");
    });
    if (name === "flags") renderFlagsView();
    if (name === "excluded") renderExcludedView();
    if (name === "sources") renderSourcesView();
    window.scrollTo({ top: 0, behavior: "auto" });
  }

  function applyHash() {
    var h = location.hash || "";
    if (h.indexOf("#offer/") === 0) {
      var id = h.slice(7);
      var entry = ENTRIES.filter(function (e) { return e.id === id; })[0];
      if (entry) {
        /* make sure the target is not filtered out */
        state.hideExpired = false;
        state.hideUnavailable = false;
        state.onlyFlagged = false;
        state.onlyNoSpend = false;
        state.q = "";
        document.getElementById("q").value = "";
        document.getElementById("hide-expired").checked = false;
        document.getElementById("hide-unavailable").checked = false;
        document.getElementById("only-flagged").checked = false;
        document.getElementById("only-no-spend").checked = false;
        state.categories.clear(); state.deals.clear(); state.levels.clear(); state.statuses.clear();
        buildFilters();
      }
      showView("browse");
      render();
    } else if (h.length > 1 && VIEWS.indexOf(h.slice(1)) !== -1) {
      showView(h.slice(1));
    } else {
      showView("browse");
    }
  }

